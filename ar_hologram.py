def build(p, e, f, sym):
    pts, mp = list(p), {}
    for i in sym:
        x, y, z = p[i]; mp[i] = len(pts); pts.append((-x, y, z))
    m = lambda i: mp.get(i, i)
    return pts, list(e)+[(m(a),m(b)) for a,b in e], list(f)+[tuple(m(i) for i in q) for q in f]

