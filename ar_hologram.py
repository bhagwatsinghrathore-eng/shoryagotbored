NAMES = list(AIRCRAFT.keys())
COLORS = [("Cyan",(255,255,0)),("HUD Green",(50,255,50)),("Magenta",(255,0,255)),("Radar Blue",(255,120,0)),("Gold",(0,215,255)),("Target Red",(60,20,255))]

cap = cv2.VideoCapture(0)
si, ci, sc, ax, ay = 0, 0, 130.0, 0.42, 0.0

while True:
    ok, f = cap.read()
    if not ok: break
    f = cv2.flip(f, 1); h, w, _ = f.shape
    cx, cy = w//2, h//2
    cname, col = COLORS[ci]
    f = cv2.addWeighted(f, 0.85, np.zeros_like(f), 0.15, 0)

    verts, edges, polys = AIRCRAFT[NAMES[si]]
    ay += 0.02
    rx = np.array(((1,0,0),(0,math.cos(ax),-math.sin(ax)),(0,math.sin(ax),math.cos(ax))))
    ry = np.array(((math.cos(ay),0,math.sin(ay)),(0,1,0),(-math.sin(ay),0,math.cos(ay))))
    pts = [(int(cx+x*sc*(4.2/(4.2+z))), int(cy+y*sc*(4.2/(4.2+z)))) for x,y,z in (np.array(verts,float)@rx.T@ry.T)]

    pl = np.zeros_like(f)
    for q in polys: cv2.fillPoly(pl, np.array([pts[i] for i in q], np.int32).reshape(1, -1, 2), col)
    f = cv2.addWeighted(f, 1.0, pl, 0.16, 0)
    hl = np.zeros_like(f)
    for i,j in edges: cv2.line(hl, pts[i], pts[j], col, 5)
    f = cv2.add(f, cv2.GaussianBlur(hl, (13,13), 0))
    for i,j in edges: cv2.line(f, pts[i], pts[j], (255,255,255), 1)
    f[::6] = (f[::6]*0.78).astype(np.uint8)

    cv2.putText(f, f"{NAMES[si]}  |  Color: {cname}  |  Size: {int(sc)}", (20,35), 0, 0.65, col, 2)
    cv2.putText(f, "[Up/Down Arrows] Size   [Left/Right or N/P] Aircraft   [C] Color   [W/S] Tilt   [Q] Quit", (20,h-18), 0, 0.5, (220,220,220), 1)
    cv2.imshow("AR Aircraft Hologram", f)

    k = cv2.waitKeyEx(16)
    if k in (ord('q'), ord('Q'), 27): break
    elif k in (63232, 2490368, 65362, ord('+'), ord('=')): sc = min(h*0.44, sc + 12)
    elif k in (63233, 2621440, 65364, ord('-'), ord('_')): sc = max(35.0, sc - 12)
    elif k in (63235, 2555904, 65363, ord('n'), ord('N')): si = (si+1)%len(NAMES)
    elif k in (63234, 2424832, 65361, ord('p'), ord('P')): si = (si-1)%len(NAMES)
    elif k in (ord('c'), ord('C')): ci = (ci+1)%len(COLORS)
    elif k in (ord('w'), ord('W')): ax -= 0.15
    elif k in (ord('s'), ord('S')): ax += 0.15

cap.release(); cv2.destroyAllWindows()
